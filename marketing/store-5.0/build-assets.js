// Writes glyphs.js (the Unicon paths the mockups use) and qr.js (real QR codes for the tickets).
// Run from a checkout with mobile/node_modules installed:  node build-assets.js [path/to/mobile]
const fs = require('fs');
const path = require('path');

const mobile = path.resolve(process.argv[2] || path.join(__dirname, '../../mobile'));
const NAMES = ['map-pin', 'bell', 'magnifying-glass', 'sliders-horizontal', 'arrow-right', 'qr-code', 'calendar-plus', 'caret-right',
  'caret-left', 'caret-up', 'ticket', 'share-network', 'heart', 'dots-three', 'check-circle', 'circle', 'minus', 'plus', 'x',
  'users-three', 'trophy', 'lightbulb', 'gavel', 'link-simple', 'door-open', 'lifebuoy', 'cloud-arrow-up', 'flashlight',
  'wifi-slash', 'confetti', 'star', 'certificate', 'arrow-up-right', 'cards', 'wallet', 'stack', 'user', 'bell-ringing', 'chart-bar', 'chats-circle'];

const glyphs = {};
for (const n of NAMES) {
  const src = fs.readFileSync(path.join(mobile, 'node_modules/@unifesto/unicon/dist/glyphs', `${n}.js`), 'utf8');
  const all = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
  glyphs[n] = { regular: all.regular, bold: all.bold, fill: all.fill };
}
fs.writeFileSync(path.join(__dirname, 'glyphs.js'),
  `// Generated by build-assets.js from @unifesto/unicon. Do not edit.\nwindow.GLYPHS = ${JSON.stringify(glyphs)};\n`);

// QR modules as a boolean matrix; the page draws them, so they stay crisp at any scale
const QRCode = require(require.resolve('qrcode', { paths: [mobile] }));
const qr = (text) => {
  const { modules } = QRCode.create(text, { errorCorrectionLevel: 'M' });
  return { size: modules.size, bits: Array.from(modules.data).join('') };
};
const codes = { ticket: qr('https://unifesto.app/t/UFS-7K2Q9'), scan: qr('https://unifesto.app/t/UFS-3MX8D') };
fs.writeFileSync(path.join(__dirname, 'qr.js'), `// Generated by build-assets.js. Do not edit.\nwindow.QR = ${JSON.stringify(codes)};\n`);
console.log(`glyphs.js: ${NAMES.length} glyphs; qr.js: ${Object.keys(codes).length} codes`);
